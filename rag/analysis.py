def response_instructions(mode='text'):
    if mode not in _INSTRUCTIONS:
        raise ValueError('Неизвестный аналитический режим: ' + str(mode))
    return _INSTRUCTIONS[mode] + '\n\nПравила источников: ' + SOURCE_POLICY


def retrieval_size(mode='text'):
    response_instructions(mode)
    return {'text': 12, 'overview': 24, 'executive': 32, 'expert': 24}[mode]
